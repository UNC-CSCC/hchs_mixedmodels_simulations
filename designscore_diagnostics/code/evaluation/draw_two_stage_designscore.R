# Standalone scientific schematic. Base R only; no models or datasets are run.
args<-commandArgs(TRUE)
root<-if(length(args)) normalizePath(args[1],winslash="/",mustWork=TRUE) else normalizePath(".",winslash="/")
dest<-file.path(root,"figures")
dir.create(dest,showWarnings=FALSE,recursive=TRUE)
draw<-function() {
  par(mar=c(0,0,0,0),xaxs="i",yaxs="i",family="sans",fg="#172D42")
  plot.new();plot.window(xlim=c(0,18),ylim=c(0,15.3))
  blue<-"#21669B";teal<-"#087C73";ink<-"#172D42";muted<-"#506477";line<-"#BAC8D3"
  box<-function(x0,y0,x1,y1,fill,border=line) rect(x0,y0,x1,y1,col=fill,border=border,lwd=1)
  label<-function(x,y,s,size=1,col=ink,font=1,...) text(x,y,s,adj=c(0,.5),cex=size,col=col,font=font,...)
  arrow<-function(x0,y0,x1,y1,col=muted) arrows(x0,y0,x1,y1,length=.10,angle=25,lwd=2,col=col)
  label(.55,14.81,"Two-stage design-score estimation: from residuals to standard errors",1.66,font=2)
  label(.55,14.31,"Correct the household variance equations, then carry uncertainty from both stages into a stratified sandwich.",1.06,col=muted)

  # Overview of information flow, distinct from the two estimation stages.
  locations<-list(c(.55,4.45),c(5.0,8.95),c(9.5,13.1),c(13.65,17.45))
  captions<-c("Subject-average\nresiduals","Household estimating\nequations","Block-group\nscore totals","Standard\nerrors")
  for(i in 1:4) {
    box(locations[[i]][1],13.04,locations[[i]][2],13.82,if(i<=2) "#EEF7F5" else "#F2F4F8")
    text(mean(locations[[i]]),13.43,captions[i],cex=1.05,font=2,col=if(i<=2) teal else ink)
    if(i<4) arrow(locations[[i]][2]+.07,13.43,locations[[i+1]][1]-.07,13.43)
  }

  # Stage 1: residual definition and first-stage parameters.
  box(.55,5.95,5.80,12.62,"#F2F7FC",border="#A7C3D9")
  box(.55,11.98,5.80,12.62,blue,border=blue)
  label(.80,12.30,"STAGE 1   Weighted mixed-model fit",1.14,col="white",font=2)
  label(.88,11.57,"Retain scenario 3's first stage",1.07,font=2,col=blue)
  label(.88,11.12,"Three visits, outcomes and covariates",1.02)
  label(.88,10.72,"Globally scaled subject weights;",1.02)
  label(.88,10.36,"original household weights; visit weights = 1",.98)
  box(.87,9.15,5.48,10.04,"white",border="#CFDEEB")
  label(1.08,9.76,"Retain these point estimates",.92,font=2,col=blue)
  label(1.08,9.39,expression(hat(beta)~"fixed effects;"~~hat(e)~"visit-residual variance"),1.04)
  label(.88,8.76,"One residual per visit:",1.01,font=2)
  label(.88,8.28,expression(R[hit]==Y[hit]-x[hit]^T*hat(beta)~~~~t==1*","*2*","*3),1.15)
  label(.88,7.76,"Average the subject's three residuals:",1.00,font=2)
  label(.88,7.22,expression(r[hi]==frac(R[hi1]+R[hi2]+R[hi3],3)),1.25)
  label(.88,6.65,"Household and subject effects remain",.96)
  label(.88,6.31,"inside these residuals.",.96)
  arrow(5.83,9.62,6.53,9.62,blue)
  text(6.18,10.03,expression(hat(beta)*","~hat(e)),cex=.94,col=blue)
  text(6.18,9.24,expression(r[hi]),cex=1.04,col=blue)

  # Stage 2: definitions and the complete equations actually solved.
  box(6.60,5.95,17.45,12.62,"#F0F8F5",border="#A9D6CE")
  box(6.60,11.98,17.45,12.62,teal,border=teal)
  label(6.87,12.30,"STAGE 2   Household estimating equations",1.18,col="white",font=2)
  label(6.93,11.60,expression("Unknowns:"~~a~"household variance;"~~b~"subject variance. Hold"~~hat(beta)*","~hat(e)~"fixed."),1.04)
  box(6.92,9.34,11.80,11.23,"white",border="#C7DED6")
  box(12.05,9.34,17.12,11.23,"white",border="#C7DED6")
  label(7.12,10.96,"Individual totals: one term per person",.96,font=2)
  label(7.12,10.44,expression(hat(N)[h]==sum(frac(1,p[hi]))),1.13)
  label(9.24,10.44,"Estimated subject count",.86)
  label(7.12,9.86,expression(hat(B)[h]==sum(frac(r[hi]^2,p[hi]))),1.13)
  label(9.24,9.86,"Total squared residuals",.86)
  label(12.25,10.96,"Within-household pairs",1.00,font=2)
  label(12.25,10.62,"Two different subjects in the same household",.87)
  label(12.25,10.03,expression(hat(Q)[h]==hat(B)[h]+2*sum(frac(r[hi]*r[hj],p[hij]),i<j)),1.09)
  label(12.25,9.49,"Estimates the full household's squared residual sum",.80)
  label(6.93,9.07,expression("Selection probabilities:"~~p[hi]~"(one subject),"~~p[hij]~"(both),"~~pi[h]~"(household)"),.96)
  label(6.93,8.67,expression(W[h]==frac(1,pi[h])~~~~d==b+frac(hat(e),3)~~~~D[h]==d+a*M[h]),1.11)
  label(13.32,8.67,expression(M[h]~"= full eligible household size"),.92)
  label(7.10,7.91,expression(hat(U)[a]==frac(1,2)*sum(W[h]*bgroup("[",frac(hat(Q)[h],D[h]^2)-frac(hat(N)[h],D[h]),"]"),h)~"= 0"),1.25)
  label(13.30,7.91,"Household-variance score",.98,font=2,col=teal)
  label(7.10,6.93,expression(hat(U)[b]==frac(1,2)*sum(W[h]*bgroup("[",frac(hat(B)[h],d^2)-frac(a*(2*d+a*M[h])*hat(Q)[h],d^2*D[h]^2)-frac(hat(N)[h],d)+frac(a*hat(N)[h],d*D[h]),"]"),h)~"= 0"),1.23)
  label(13.30,6.93,"Subject-variance score",.98,font=2,col=teal)
  label(6.93,6.32,"Solve jointly for a and b: balance weighted residual information with model predictions.",.96)

  # Both stages feed the same household stack, then scores are aggregated by PSU.
  segments(12.02,5.92,12.02,5.55,col=teal,lwd=2)
  segments(3.17,5.55,12.02,5.55,col=teal,lwd=2)
  arrow(3.17,5.92,3.17,5.19,blue)
  label(7.48,5.75,"Both stages feed one household stack",.87,col=muted)

  box(.55,1.55,5.80,5.19,"#F2F4F8")
  box(6.60,1.55,11.80,5.19,"#F2F4F8")
  box(12.60,1.55,17.45,5.19,"#F2F4F8")
  label(.85,4.83,"STACK BOTH STAGES",.98,font=2,col=blue)
  label(6.9,4.83,"BLOCK-GROUP SCORE TOTALS",.98,font=2,col=teal)
  label(12.88,4.83,"STANDARD ERRORS",.98,font=2,col=blue)
  label(.85,4.36,"One 13-element vector per household:",.98,font=2)
  label(.85,3.95,"7 fixed-effect + 3 first-stage variance equations",.91)
  label(.85,3.55,"+ 1 weight-normalization equation",.91)
  label(.85,3.15,"+ 2 weighted stage-2 household score terms",.91)
  label(.85,2.58,expression(psi[h]==bgroup("(",bgroup("(",S[h]^{(1)},")")^T*","~g[c*h]*","~hat(U)[a*","*h]*","~hat(U)[b*","*h],")")^T),1.10)
  label(.85,2.08,"The last two entries are summands of",.88)
  label(.85,1.78,"the equations above. Keep visit deviations in stage 1.",.84)
  arrow(5.84,3.45,6.55,3.45)

  label(6.90,4.23,expression(Psi[gk]==sum(psi[h],h%in%bgroup("(",g*","*k,")"))),1.20)
  label(6.90,3.78,"Sum households within each block group k.",.91)
  label(6.90,3.48,expression(bar(Psi)[g]~"= mean block-group score in stratum g"),.81)
  label(6.90,3.22,expression(Delta[gk]==Psi[gk]-bar(Psi)[g]),1.17)
  label(6.90,2.62,expression(M==sum(frac(m[g],m[g]-1)*sum(Delta[gk]*Delta[gk]^T,k),g)),1.09)
  label(6.90,2.08,expression(m[g]~"= number of block groups in stratum g"),.85)
  label(6.90,1.78,"Meat matrix M uses design strata, not age groups.",.84)
  arrow(11.84,3.45,12.55,3.45)

  label(12.88,4.20,expression(A==-frac(partialdiff*sum(psi[h],h),partialdiff*theta^T)),1.12)
  label(12.88,3.52,expression(hat(V)[theta]==A^{-1}*M*A^{-T}),1.20)
  label(12.88,2.96,expression(SE(hat(theta)[j])==sqrt(bgroup("(",hat(V)[theta],")")[jj])),1.12)
  label(12.88,2.42,"Differentiate the full stack: changing",.88)
  label(12.88,2.08,expression(beta~"recomputes residuals;"~~e~"changes scores."),.88)
  label(12.88,1.78,expression(theta~"has 13 parameters; variances use log scale."),.80)

  label(.55,1.04,"Target: one common household variance and one common subject variance",1.12,font=2,col=teal)
  label(.55,.65,"Individual and pair sums use sampled subjects within each household. Zero-score equations describe an interior solution; boundaries use one-sided conditions.",.87,col=muted)
  label(.55,.29,"Scores recover census scores in expectation at fixed parameters. The block-group sandwich is a with-replacement approximation; finite-sample bias and coverage still need checking.",.84,col=muted)
}
png(file.path(dest,"two_stage_designscore.png"),width=2700,height=2295,res=150,type="cairo",pointsize=12,bg="white")
draw();invisible(dev.off())
svg(file.path(dest,"two_stage_designscore.svg"),width=18,height=15.3,pointsize=12,bg="white")
draw();invisible(dev.off())
cat("Wrote expanded PNG and SVG to",dest,"\n")

